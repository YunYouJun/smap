export type DomainMessageKey = keyof typeof enDomainMessages

const domainMessageLookup: Readonly<Record<string, string>> = enDomainMessages

export function translateDomainText(value: string, locale: SmapLocale): string {
  if (locale === 'zh-CN')
    return value

  const translated = domainMessageLookup[value]
  if (translated)
    return translated

  const translatedPrefixes: ReadonlyArray<readonly [string, string]> = [
    ['正在前往 ', 'Heading to '],
    ['补给窗口 · ', 'Supply window · '],
    ['通过 ', 'Passing '],
    ['航行服务 · ', 'Navigation service · '],
    ['航线提醒 · ', 'Route alert · '],
  ]

  for (const [prefix, translatedPrefix] of translatedPrefixes) {
    if (value.startsWith(prefix))
      return `${translatedPrefix}${translateDomainText(value.slice(prefix.length), locale)}`
  }

  return value
    .replace(/(\d+(?:\.\d+)?) 光时/g, '$1 light-hours')
    .replace(/(\d+(?:\.\d+)?) 光分/g, '$1 light-minutes')
    .replace(/(\d+) 个跃迁点/g, '$1 jump points')
    .replace(/(\d+) 星币/g, '$1 credits')
}
